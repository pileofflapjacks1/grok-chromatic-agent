#!/usr/bin/env python3
"""
GB Studio project scaffolder for Chromatic / GBC development.

Creates a clean folder structure + starter .gbsproj that you can open in GB Studio.
GB Studio will complete initialization (player sprite, default palettes, etc.) on first open.

Usage:
    python scripts/generate_basic_project.py MyGame /path/to/parent [--type topdown|platform]

Examples:
    python scripts/generate_basic_project.py MoonGarden ~/Games --type topdown
    python scripts/generate_basic_project.py JumpMan ~/Games --type platform
"""

import argparse
import json
import uuid
from pathlib import Path

def main():
    parser = argparse.ArgumentParser(description="Scaffold a GB Studio project")
    parser.add_argument("name", help="Project name")
    parser.add_argument("parent", help="Parent folder to create the project in")
    parser.add_argument("--type", choices=["topdown", "platform"], default="topdown",
                        help="Scene type preference (default: topdown)")
    args = parser.parse_args()

    name = args.name
    parent = Path(args.parent).expanduser().resolve()
    project_dir = parent / name
    project_dir.mkdir(parents=True, exist_ok=True)

    scene_type = "TOPDOWN" if args.type == "topdown" else "PLATFORM"

    # Minimal but structured .gbsproj
    project = {
        "_resourceType": "project",
        "name": name,
        "author": "",
        "_version": "4.0.0",
        "sceneTypes": [scene_type],
        "startSceneId": "",
        "startX": 8,
        "startY": 8,
        "startDirection": "down",
        "startMoveSpeed": 1,
        "startAnimSpeed": 15,
        "colorMode": "color",
        "defaultPlayerSpritesheetId": "",
        "defaultPlayerPaletteId": "",
        "defaultBackgroundPaletteIds": [],
        "defaultSpritePaletteIds": [],
        "musicDriver": "gbtplayer",
        "engineFields": {},
        "variables": [],
        "constants": [],
        "prefabs": [],
        "scenes": [],
        "backgrounds": [],
        "spriteSheets": [],
        "tilesets": [],
        "fonts": [],
        "avatars": [],
        "emotes": [],
        "sounds": [],
        "music": [],
        "palettes": [],
        "scriptEvents": [],
        "customEvents": []
    }

    gbsproj_path = project_dir / f"{name}.gbsproj"
    with open(gbsproj_path, "w") as f:
        json.dump(project, f, indent=2)

    # Folder structure GB Studio expects / benefits from
    folders = [
        "assets/backgrounds",
        "assets/sprites",
        "assets/ui",
        "assets/music",
        "assets/sounds",
        "project",
        "build"
    ]
    for folder in folders:
        (project_dir / folder).mkdir(parents=True, exist_ok=True)

    # Project README with next steps
    readme = f"""# {name}

Scaffolded GB Studio project ({args.type} style).

## Next Steps

1. Open `{name}.gbsproj` in [GB Studio](https://www.gbstudio.dev/).
2. Let GB Studio finish initialization (it will add default player, palettes, etc.).
3. Create your first scene and set it as the starting scene.
4. Add a player actor and basic movement/dialogue.
5. Build and test in the emulator, then (optionally) stream/flash to Chromatic.

## Tips

- Prefer short scenes and simple art for the first playable version.
- Check hardware limits (tiles, sprites, palettes) before adding lots of graphics.
- Use the Grok Chromatic skill for iteration help.

Generated by grok-chromatic-agent.
"""
    (project_dir / "README.md").write_text(readme)

    print(f"\nCreated project: {project_dir}")
    print(f"  Type: {args.type} ({scene_type})")
    print(f"  Open this file in GB Studio: {gbsproj_path}")
    print("\nNext: open in GB Studio, let it initialize, then start adding scenes.")
    print("Use the Grok Chromatic skill to help flesh out the game.\n")

if __name__ == "__main__":
    main()
